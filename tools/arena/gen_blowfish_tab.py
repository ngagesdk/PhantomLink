#!/usr/bin/env python3
"""Generate server/src/gcs_blowfish_tab.h: the Blowfish start values.

Blowfish initialises its P-array (18 words) and S-boxes (4 x 256 words)
with the fractional part of pi in hexadecimal.  This computes the digits
with integer arithmetic (Machin's formula) instead of copying a table.

    python3 tools/arena/gen_blowfish_tab.py > server/src/gcs_blowfish_tab.h
"""

WORDS = 18 + 4 * 256


def pi_hex_digits(n):
    bits = n * 4 + 64
    one = 1 << bits

    def arctan_inv(x):
        total, term, k, x2, sign = 0, one // x, 1, x * x, 1
        while term:
            total += sign * (term // k)
            term //= x2
            k += 2
            sign = -sign
        return total

    pi = 16 * arctan_inv(5) - 4 * arctan_inv(239)
    frac = pi - (3 << bits)
    return format(frac >> 64, 'x').zfill(n)[:n]


def main():
    h = pi_hex_digits(WORDS * 8)
    words = [h[i * 8:(i + 1) * 8] for i in range(WORDS)]
    # known values: first P word, first S-box word, last S-box word
    assert words[0] == '243f6a88' and words[18] == 'd1310ba6' and words[-1] == '3ac372e6'
    print('/** @file gcs_blowfish_tab.h')
    print(' *')
    print(' *  Blowfish start values: the P-array (18 words) followed by the four')
    print(' *  S-boxes (256 words each), i.e. the fractional part of pi in hex.')
    print(' *  Generated by tools/arena/gen_blowfish_tab.py, do not edit.')
    print(' *')
    print(' *  SPDX-License-Identifier: MIT')
    print(' *')
    print(' **/')
    print()
    print('#ifndef GCS_BLOWFISH_TAB_H')
    print('#define GCS_BLOWFISH_TAB_H')
    print()
    print('static const unsigned int GCS_BF_PI[%d] = {' % WORDS)
    for i in range(0, WORDS, 6):
        print('    ' + ', '.join('0x%su' % w for w in words[i:i + 6]) + ',')
    print('};')
    print()
    print('#endif /* GCS_BLOWFISH_TAB_H */')


if __name__ == '__main__':
    main()
